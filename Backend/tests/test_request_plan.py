import pytest
from app.services.request_plan import split_requests

@pytest.mark.parametrize('text,expected',[
 ('와이파이 켜고 밝기 낮춰줘',('와이파이 켜줘','밝기 낮춰줘')),
 ('와이파이 켜줘 그리고 블루투스 꺼줘',('와이파이 켜줘','블루투스 꺼줘')),
 ('글자 크기 키우고 화면 밝기 낮추고 미디어 음량 높여줘',('글자 크기 키워줘','화면 밝기 낮춰줘','미디어 음량 높여줘')),
 ('와이파이 켜줘; 친구에게 메시지 보내줘',('와이파이 켜줘','친구에게 메시지 보내줘')),
 ('소리 및 진동 설정 열어줘',('소리 및 진동 설정 열어줘',)),
 ('와이파이 켜고 싶어',('와이파이 켜고 싶어',)),
 ('와이파이가 켜지고 있는지 확인해줘',('와이파이가 켜지고 있는지 확인해줘',)),
 ('와이파이 켜지면 밝기 낮추고 블루투스 꺼줘',('와이파이 켜지면 밝기 낮추고 블루투스 꺼줘',)),
 ('와이파이 켜고 블루투스는 끄지 마',('와이파이 켜고 블루투스는 끄지 마',)),
 ('글자는 키우지 말고 밝기만 올려줘',('글자는 키우지 말고 밝기만 올려줘',)),
 ('와이파이 켜지 말고 블루투스만 켜줘',('와이파이 켜지 말고 블루투스만 켜줘',)),
 ('와이파이 켜고 블루투스는 안 켜줘',('와이파이 켜고 블루투스는 안 켜줘',)),
 ('와이파이 켜고 꺼줘',('와이파이 켜고 꺼줘',)),
])
def test_explicit_independent_goals_only(text,expected):assert split_requests(text)==expected
